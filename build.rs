//! Embeds provider logos from `data/icons/*.png` into the binary as a static table.
//! The sync pipeline copies the PNGs for shipped providers from upstream's
//! `public/providers/`; see tools/sync-upstream/convert.mjs.

use std::env;
use std::fs;
use std::path::Path;

fn main() {
    let icons_dir = Path::new("data/icons");
    println!("cargo:rerun-if-changed=data/icons");
    let mut names: Vec<String> = fs::read_dir(icons_dir)
        .map(|rd| {
            rd.filter_map(|e| e.ok())
                .map(|e| e.file_name().to_string_lossy().to_string())
                .filter(|n| n.ends_with(".png"))
                .collect()
        })
        .unwrap_or_default();
    names.sort();
    let root = env::current_dir().expect("cwd");
    let mut out =
        String::from("/// (provider id, PNG bytes), generated by build.rs.\npub static ICONS: &[(&str, &[u8])] = &[\n");
    for n in &names {
        let id = n.trim_end_matches(".png");
        let path = root.join(icons_dir).join(n);
        out.push_str(&format!("    ({:?}, include_bytes!({:?})),\n", id, path.display().to_string()));
    }
    out.push_str("];\n");
    let dest = Path::new(&env::var("OUT_DIR").expect("OUT_DIR")).join("icons.rs");
    fs::write(dest, out).expect("write icons.rs");
}
